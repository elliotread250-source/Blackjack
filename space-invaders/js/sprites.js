// pre-render bitmaps as white sprites
SI.sprite = (rows) => {
  const c = document.createElement('canvas');
  c.width = rows[0].length; c.height = rows.length;
  const g = c.getContext('2d');
  g.fillStyle = '#fff';
  rows.forEach((r, j) => [...r].forEach((ch, i) => { if (ch === '#') g.fillRect(i, j, 1, 1); }));
  return c;
};
SI.mask = (rows) => rows.map((r) => [...r].map((ch) => (ch === '#' ? 1 : 0)));
