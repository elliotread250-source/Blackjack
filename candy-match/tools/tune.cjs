#!/usr/bin/env node
/* Calibrates move limits and star scores from bot play.   node tools/tune.cjs [--write] [--seeds=16]
 *
 * "blind" = a decent player: picks the best-looking swap but cannot see the future refills.
 * moves  = the larger of 1.6 (level 1) .. 1.2 (level 40) x the blind bot's 80th-percentile
 *          moves-to-goal and 2.2 .. 1.6 x the oracle bot's (clamped to 15..42), so the oracle bot
 *          always has a wide margin and the decent player usually wins.
 * stars  = percentiles of the blind bot's final score on that move limit: star 2 about the
 *          median win, star 3 about the 85th percentile, which in practice takes specials
 *          and finishing with moves in hand for the leftover-moves bonus.
 * Score goals: the target (star 1) is the 25th percentile of the score the blind bot has
 * after the full move limit, scaled by 0.55 (level 1) to 0.75 (level 40).
 */
'use strict';
const path = require('path');
const fs = require('fs');
const args = process.argv.slice(2);
const SEEDS = +((args.find(a => a.startsWith('--seeds=')) || '--seeds=16').split('=')[1]);
const WRITE = args.includes('--write');
const pct = (arr, p) => { const a = arr.slice().sort((x, y) => x - y); return a[Math.min(a.length - 1, Math.floor(p * a.length))]; };
const round = v => v < 3000 ? Math.round(v / 100) * 100 : v < 20000 ? Math.round(v / 500) * 500 : Math.round(v / 1000) * 1000;

(async () => {
  const { BASE_LEVELS } = await import(path.join(__dirname, '..', 'js', 'levels.js'));
  const { playLevel } = await import(path.join(__dirname, '..', 'js', 'bot.js'));
  const tune = {};
  const only = (args.find(a => a.startsWith('--level=')) || '').split('=')[1];
  console.log('lvl  goal                         moves  stars');
  for (const base of BASE_LEVELS) {
    if (only && +only !== base.n) continue;
    const g0 = base.goal;
    const gOther = { ...g0 }; delete gOther.score;
    const hasOther = Object.keys(gOther).length > 0;
    const run = (level, seed, cap) => playLevel(level, seed, { mode: 'blind', cap });
    let M = base.moves, rawP80 = '-';
    if (hasOther) {
      const ttw = [], tto = [];
      for (let s = 1; s <= SEEDS; s++) {
        ttw.push(run({ ...base, goal: gOther }, s, 70).turnsToGoal ?? 70);
        tto.push(playLevel({ ...base, goal: gOther }, s, { mode: 'oracle', depth: 2, cap: 70 }).turnsToGoal ?? 70);
      }
      rawP80 = pct(ttw, 0.8) + '/' + pct(tto, 0.8);
      const k = (base.n - 1) / 39;
      M = Math.max(base.minMoves || 15, Math.min(42, Math.ceil(Math.max((1.6 - 0.4 * k) * pct(ttw, 0.8), (2.2 - 0.6 * k) * pct(tto, 0.8)))));
    }
    let s1 = 1000;
    if (g0.score) {
      const sc = [];
      for (let s = 1; s <= SEEDS; s++) sc.push(run({ ...base, moves: M, goal: { ...gOther, score: 1e9 } }, s, M).st.score);
      s1 = round(pct(sc, 0.25) * (0.55 + 0.2 * (base.n - 1) / 39) * (hasOther ? 0.8 : 1));
    }
    const lv = { ...base, moves: M, goal: { ...g0, ...(g0.score ? { score: s1 } : {}) }, stars: [s1, s1 * 2, s1 * 3] };
    const win = [];
    let wins = 0;
    for (let s = 101; s < 101 + SEEDS * 2; s++) {
      const r = run(lv, s, null);
      if (r.won) { wins++; win.push(r.st.score); }
    }
    let s2 = win.length ? round(pct(win, 0.5)) : s1 * 2, s3 = win.length ? round(pct(win, 0.85)) : s1 * 3;
    if (!g0.score) s1 = round(s2 * 0.6);
    if (s2 <= s1) s2 = round(s1 * 1.3);
    if (s3 <= s2) s3 = round(s2 * 1.25);
    tune[base.n] = { moves: M, stars: [s1, s2, s3] };
    console.log(String(base.n).padStart(3), JSON.stringify(g0).padEnd(28), String(M).padStart(4), ' ', [s1, s2, s3].join('/').padEnd(18), 'ttw80', String(rawP80).padStart(6), ' blind wins', wins + '/' + SEEDS * 2);
  }
  if (WRITE && !only) {
    const body = '// Generated by tools/tune.cjs (node tools/tune.cjs --write): move limits and star scores per level number.\nexport const TUNE = ' +
      JSON.stringify(tune, null, 1).replace(/\n\s+/g, ' ').replace(/ \}/g, ' }').replace(/^\{ /, '{\n ').replace(/\}, "/g, '},\n "') + ';\n';
    fs.writeFileSync(path.join(__dirname, '..', 'js', 'tuning.js'), body);
    console.log('wrote js/tuning.js');
  }
})();
