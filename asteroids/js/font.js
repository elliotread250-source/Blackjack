/*
 * Vector font in the style of the Atari 1979 vector games: every glyph is a
 * few strokes on an 8 x 12 grid, drawn with the same glowing lines as the
 * ships and rocks. Coordinates here are y-up (0 = baseline, 12 = cap height)
 * the way the arcade's character ROM thinks of them; they are flipped to
 * screen space once at load time.
 */
(function () {
  'use strict';

  const R = [[0, 0], [8, 0], [8, 12], [0, 12], [0, 0]];
  const RAW = {
    '0': [R],
    '1': [[[4, 0], [4, 12]]],
    '2': [[[0, 12], [8, 12], [8, 7], [0, 5], [0, 0], [8, 0]]],
    '3': [[[0, 12], [8, 12], [8, 0], [0, 0]], [[0, 6], [8, 6]]],
    '4': [[[0, 12], [0, 6], [8, 6]], [[8, 12], [8, 0]]],
    '5': [[[8, 12], [0, 12], [0, 7], [8, 5], [8, 0], [0, 0]]],
    '6': [[[0, 12], [0, 0], [8, 0], [8, 5], [0, 7]]],
    '7': [[[0, 12], [8, 12], [8, 6], [4, 0]]],
    '8': [R, [[0, 6], [8, 6]]],
    '9': [[[8, 0], [8, 12], [0, 12], [0, 7], [8, 5]]],
    A: [[[0, 0], [0, 8], [4, 12], [8, 8], [8, 0]], [[0, 4], [8, 4]]],
    B: [[[0, 0], [0, 12], [4, 12], [8, 10], [4, 6], [8, 2], [4, 0], [0, 0]]],
    C: [[[8, 0], [0, 0], [0, 12], [8, 12]]],
    D: [[[0, 0], [0, 12], [4, 12], [8, 8], [8, 4], [4, 0], [0, 0]]],
    E: [[[8, 0], [0, 0], [0, 12], [8, 12]], [[0, 6], [6, 6]]],
    F: [[[0, 0], [0, 12], [8, 12]], [[0, 6], [6, 6]]],
    G: [[[6, 6], [8, 4], [8, 0], [0, 0], [0, 12], [8, 12]]],
    H: [[[0, 0], [0, 12]], [[0, 6], [8, 6]], [[8, 12], [8, 0]]],
    I: [[[0, 0], [8, 0]], [[4, 0], [4, 12]], [[0, 12], [8, 12]]],
    J: [[[0, 4], [4, 0], [8, 0], [8, 12]]],
    K: [[[0, 0], [0, 12]], [[8, 12], [0, 6], [6, 0]]],
    L: [[[8, 0], [0, 0], [0, 12]]],
    M: [[[0, 0], [0, 12], [4, 8], [8, 12], [8, 0]]],
    N: [[[0, 0], [0, 12], [8, 0], [8, 12]]],
    O: [R],
    P: [[[0, 0], [0, 12], [8, 12], [8, 6], [0, 5]]],
    Q: [[[0, 0], [0, 12], [8, 12], [8, 4], [0, 0]], [[4, 4], [8, 0]]],
    R: [[[0, 0], [0, 12], [8, 12], [8, 6], [0, 5]], [[4, 5], [8, 0]]],
    S: [[[0, 2], [2, 0], [8, 0], [8, 5], [0, 7], [0, 12], [6, 12], [8, 10]]],
    T: [[[0, 12], [8, 12]], [[4, 12], [4, 0]]],
    U: [[[0, 12], [0, 2], [4, 0], [8, 2], [8, 12]]],
    V: [[[0, 12], [4, 0], [8, 12]]],
    W: [[[0, 12], [2, 0], [4, 4], [6, 0], [8, 12]]],
    X: [[[0, 0], [8, 12]], [[0, 12], [8, 0]]],
    Y: [[[0, 12], [4, 6], [8, 12]], [[4, 6], [4, 0]]],
    Z: [[[0, 12], [8, 12], [0, 0], [8, 0]], [[2, 6], [6, 6]]],
    ' ': [],
    '-': [[[2, 6], [6, 6]]],
    '_': [[[0, 0], [8, 0]]],
    '.': [[[3.5, 0], [4.5, 0], [4.5, 1], [3.5, 1], [3.5, 0]]],
    ',': [[[4.5, 1], [3, -2]]],
    ':': [[[4, 2.5], [4, 3.5]], [[4, 8.5], [4, 9.5]]],
    '!': [[[4, 4], [4, 12]], [[4, 0], [4, 1]]],
    '?': [[[0, 8], [4, 12], [8, 8], [4, 4], [4, 3]], [[4, 0], [4, 1]]],
    "'": [[[4, 12], [4, 9]]],
    '/': [[[0, 0], [8, 12]]],
    '(': [[[6, 12], [2, 8], [2, 4], [6, 0]]],
    ')': [[[2, 12], [6, 8], [6, 4], [2, 0]]],
    '+': [[[4, 2], [4, 10]], [[0, 6], [8, 6]]],
    '=': [[[1, 4], [7, 4]], [[1, 8], [7, 8]]],
    '<': [[[6, 11], [1, 6], [6, 1]]],
    '>': [[[2, 11], [7, 6], [2, 1]]],
    '^': [[[1, 6], [4, 11], [7, 6]], [[4, 11], [4, 1]]],
    '*': [[[4, 1], [4, 11]], [[0, 6], [8, 6]], [[1, 2], [7, 10]], [[1, 10], [7, 2]]],
    '#': [[[2, 0], [3, 12]], [[5, 0], [6, 12]], [[0, 4], [8, 4]], [[0, 8], [8, 8]]],
    '©': [[[2, -1], [6, -1], [9, 2], [9, 10], [6, 13], [2, 13], [-1, 10], [-1, 2], [2, -1]],
      [[6, 3], [2, 3], [2, 9], [6, 9]]],
  };

  // Flip to y-down: (0,0) is the top-left of the cap box.
  const GLYPHS = {};
  for (const ch of Object.keys(RAW)) {
    GLYPHS[ch] = RAW[ch].map((stroke) => stroke.map((p) => [p[0], 12 - p[1]]));
  }

  const ADV = 12; // advance per character in grid units (8 wide + 4 gap)

  /** Width in world units of `str` at cap height `size`. */
  function measure(str, size) {
    if (!str.length) return 0;
    const s = size / 12;
    return (str.length * ADV - 4) * s;
  }

  /**
   * Emit strokes for `str` to `out(x1, y1, x2, y2)`. (x, y) is the top of the
   * cap box; align is 'left' | 'center' | 'right'.
   */
  function text(out, str, x, y, size, align) {
    const s = size / 12;
    const w = measure(str, size);
    let cx = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
    for (let i = 0; i < str.length; i++) {
      const g = GLYPHS[str[i]] || GLYPHS[str[i].toUpperCase()];
      if (g) {
        for (const stroke of g) {
          for (let j = 1; j < stroke.length; j++) {
            out(cx + stroke[j - 1][0] * s, y + stroke[j - 1][1] * s, cx + stroke[j][0] * s, y + stroke[j][1] * s);
          }
        }
      }
      cx += ADV * s;
    }
    return w;
  }

  window.VFont = { measure, text, GLYPHS };
})();
